using Benchmark.Dynamic.Core;
using Benchmark.Dynamic.UI;
using Xunit;

namespace Benchmark.Dynamic.Tests;

public sealed class AiReviewQueryDumpWriterTests : IDisposable {
    private readonly string testDir;

    public AiReviewQueryDumpWriterTests() {
        var baseDir = Path.Combine(AppContext.BaseDirectory, "Work", "TestAiReviewDumps");
        this.testDir = Path.Combine(baseDir, Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(this.testDir);
    }

    public void Dispose() {
        try {
            if (Directory.Exists(this.testDir)) {
                Directory.Delete(this.testDir, true);
            }
        } catch {
        }
    }

    [Fact]
    public void PromptRulesFile_IsCreatedOnInitialization() {
        using var writer = new AiReviewQueryDumpWriter(this.testDir, chunkSize: 10);
        var rulesPath = Path.Combine(writer.OutputDirectory, "00_PROMPT_RULES.md");
        Assert.True(File.Exists(rulesPath));

        var content = File.ReadAllText(rulesPath);
        Assert.Contains("FLinq 固有のアーキテクチャ・厳守ルール", content);
        Assert.Contains("8 つの観点", content);
        Assert.Contains("stackalloc / [InlineArray(16)]", content);
    }

    [Fact]
    public void Chunks_AreRotatedAndNamedCorrectly() {
        using var writer = new AiReviewQueryDumpWriter(this.testDir, chunkSize: 2, filter: AiReviewDumpFilter.AllStages);

        var m = new List<動的ライブ計測> {
            new("System.Linq", 100.0, 128.0),
            new("FLinq", 40.0, 0.0),
        };

        for (var i = 1; i <= 5; i++) {
            var item = new 動的ライブ結果(
                動的ライブ段階.ランダム探索,
                i,
                $"Q_{i}",
                SourceTarget.SystemArray,
                QueryElementType.Int,
                Seed256.Parse("0x1234"),
                16,
                WorkerExecutionStatus.Succeeded,
                $"source.Select(x => x * {i}).Sum()",
                "int generated() => 42;",
                $"// Source: Test.cs\nint RunFLinqCore() => {i};",
                "診断なし",
                true,
                "// repro",
                m);
            writer.Write(item);
        }

        var files = Directory.GetFiles(writer.OutputDirectory, "part_*.txt").OrderBy(x => x).ToArray();
        Assert.Equal(3, files.Length);

        // part_0001: 1..2, part_0002: 3..4, part_0003: 5..6
        Assert.Contains("part_0001_q000001_000002.txt", Path.GetFileName(files[0]));
        Assert.Contains("part_0002_q000003_000004.txt", Path.GetFileName(files[1]));
        Assert.Contains("part_0003_q000005_000006.txt", Path.GetFileName(files[2]));

        var part1 = File.ReadAllText(files[0]);
        Assert.Contains("# FLinq 展開コード 理想形チェック依頼 (Part 0001: #1 ～ #2)", part1);
        Assert.Contains("[ペア #1] QueryId: Q_1", part1);
        Assert.Contains("[ペア #2] QueryId: Q_2", part1);
        Assert.DoesNotContain("[ペア #3] QueryId: Q_3", part1);
    }

    [Fact]
    public void CleanExpandedSource_RemovesUnwantedHeadersAndTraces() {
        var rawSource = @"// <auto-generated />
// Source: InterceptsLocationAttribute.g.cs
namespace Intercept { internal class InterceptsLocationAttribute : Attribute {} }
// Source: TestQuery.cs
// FLinqOptimizationTrace: eyJzdGVwIjoxfQ==
public static class Generated {
    public static int RunFLinqCore(int[] src) {
        return src.Length;
    }
}";
        var cleaned = AiReviewQueryDumpWriter.CleanExpandedSource(rawSource);
        Assert.DoesNotContain("InterceptsLocationAttribute", cleaned);
        Assert.DoesNotContain("FLinqOptimizationTrace", cleaned);
        Assert.Contains("RunFLinqCore", cleaned);
    }

    [Fact]
    public void Filter_RandomOnly_And_NeedsImprovementOnly() {
        using var randomWriter = new AiReviewQueryDumpWriter(this.testDir, chunkSize: 10, filter: AiReviewDumpFilter.RandomOnly);

        var goodMetrics = new List<動的ライブ計測> {
            new("System.Linq", 100.0, 100.0),
            new("FLinq", 50.0, 0.0),
        };
        var badMetrics = new List<動的ライブ計測> {
            new("System.Linq", 100.0, 0.0),
            new("FLinq", 200.0, 100.0),
        };

        var pairStage = new 動的ライブ結果(
            動的ライブ段階.ペア全組み合わせ, 1, "P1", SourceTarget.SystemArray, QueryElementType.Int,
            default, 16, WorkerExecutionStatus.Succeeded, "x", "s", "e", "", true, "", goodMetrics);

        var randomGood = new 動的ライブ結果(
            動的ライブ段階.ランダム探索, 2, "R1", SourceTarget.SystemArray, QueryElementType.Int,
            default, 16, WorkerExecutionStatus.Succeeded, "x", "s", "e", "", true, "", goodMetrics);

        var randomBad = new 動的ライブ結果(
            動的ライブ段階.ランダム探索, 3, "R2", SourceTarget.SystemArray, QueryElementType.Int,
            default, 16, WorkerExecutionStatus.Succeeded, "x", "s", "e", "", true, "", badMetrics);

        Assert.False(randomWriter.ShouldDump(pairStage));
        Assert.True(randomWriter.ShouldDump(randomGood));
        Assert.True(randomWriter.ShouldDump(randomBad));

        using var improveWriter = new AiReviewQueryDumpWriter(this.testDir, chunkSize: 10, filter: AiReviewDumpFilter.NeedsImprovementOnly);
        Assert.False(improveWriter.ShouldDump(randomGood));
        Assert.True(improveWriter.ShouldDump(randomBad));
    }
}
