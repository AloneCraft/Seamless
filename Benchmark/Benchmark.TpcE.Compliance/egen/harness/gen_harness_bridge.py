"""
EGen の TxnHarnessDBInterface.h から、次の 2 つを生成する開発用スクリプト。
  - HarnessBridge.g.h  : 全フレームの純粋仮想関数を実装し、C# のコールバックへ中継する C++ のクラスと、取引ごとの実行関数。
  - HarnessFrames.g.cs : フレーム ID の列挙型と、フレームごとの入力・出力の構造体名、取引 ID。

使い方: python gen_harness_bridge.py <EGen の展開先> <出力の .g.h> <出力の .g.cs>
"""
import os
import re
import sys

egen = sys.argv[1]
out_h = sys.argv[2]
out_cs = sys.argv[3]

text = open(os.path.join(egen, "inc", "TxnHarnessDBInterface.h"), encoding="utf-8", errors="replace").read()
text = re.sub(r"//.*", "", text)
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)

# class C<Name>DBInterface { virtual void Do<Name>Frame<N>(...) = 0; ... }
interfaces = []  # (txn, [frames])
for m in re.finditer(r"class\s+C(\w+)DBInterface\s*\{(.*?)\n\};", text, re.S):
    txn = m.group(1)
    frames = []
    for f in re.finditer(r"virtual\s+void\s+(Do\w+Frame(\d+))\s*\(([^)]*)\)\s*=\s*0;", m.group(2)):
        params = [p.strip() for p in f.group(3).split(",") if p.strip() and p.strip() != "void"]
        parsed = []
        for p in params:
            pm = re.match(r"(?:const\s+)?(\w+)\s*\*\s*(\w+)", p)
            parsed.append((pm.group(1), pm.group(2), p.startswith("const")))
        frames.append((f.group(1), int(f.group(2)), parsed))
    interfaces.append((txn, frames))

txn_order = [t for t, _ in interfaces]
needs_market = {"TradeOrder", "MarketFeed"}

# ---- C++ -----------------------------------------------------------------------------------------------------------
h = []
w = h.append
w("// <auto-generated> gen_harness_bridge.py が EGen の TxnHarnessDBInterface.h から生成した。手で直さない。 </auto-generated>")
w("#pragma once")
for txn in txn_order:
    w('#include "TxnHarness%s.h"' % txn)
w("#include <stdexcept>")
w("namespace HarnessBridge {")
w("using namespace TPCE;")
w("typedef int (__cdecl *FrameCallback)(int frameId,const void* input,void* output);")
w("typedef int (__cdecl *SendCallback)(const void* tradeRequest);")
w("struct BridgeFailure : std::runtime_error { int code; explicit BridgeFailure(int c) : std::runtime_error(\"the frame callback failed\"), code(c) {} };")
w("class Bridge")
bases = ["public C%sDBInterface" % t for t in txn_order] + ["public CSendToMarketInterface"]
w("    : " + ",\n      ".join(bases))
w("{")
w("    FrameCallback m_frame;")
w("    SendCallback m_send;")
w("    void Call(int id,const void* in,void* out){ int rc=m_frame(id,in,out); if(rc!=0){ throw BridgeFailure(rc); } }")
w("public:")
w("    Bridge(FrameCallback frame,SendCallback send) : m_frame(frame), m_send(send) {}")
w("protected:")
w("    bool SendToMarket(TTradeRequest& request) override { return m_send(&request)!=0; }")
w("public:")
frame_id = 0
frame_table = []  # (id, txn, name, number, input, output)
for txn, frames in interfaces:
    for name, number, params in frames:
        in_type = None
        out_type = None
        sig = []
        for ptype, pname, is_const in params:
            if ptype == "CSendToMarketInterface":
                sig.append("CSendToMarketInterface *")
            elif is_const:
                in_type = ptype
                sig.append("const %s *pIn" % ptype)
            else:
                out_type = ptype
                sig.append("%s *pOut" % ptype)
        # MarketFeed の第 3 引数(送信先)は受け取って捨てる(送信は SendToMarket のコールバックで集める)
        sig_text = ", ".join(sig)
        call_in = "pIn"
        if in_type is None:
            call_in = "nullptr"
        call_out = "pOut"
        if out_type is None:
            call_out = "nullptr"
        w("    void %s(%s) override { Call(%d,%s,%s); }" % (name, sig_text, frame_id, call_in, call_out))
        frame_table.append((frame_id, txn, name, number, in_type, out_type))
        frame_id += 1
w("};")
w("// 取引ごとの実行。戻り値は出力の status(失敗の例外は呼び出し側で受ける)。")
w("inline int RunTransaction(Bridge& bridge,int txnId,const void* input,void* output){")
w("    switch(txnId){")
for index, txn in enumerate(txn_order):
    w("    case %d:{" % index)
    if txn in needs_market:
        w("        C%s harness(&bridge,&bridge);" % txn)
    else:
        w("        C%s harness(&bridge);" % txn)
    w("        harness.DoTxn((P%sTxnInput)const_cast<void*>(input),(P%sTxnOutput)output);" % (txn, txn))
    w("        return ((P%sTxnOutput)output)->status;" % txn)
    w("    }")
w("    default: return -1000;")
w("    }")
w("}")
w("}  // namespace HarnessBridge")
open(out_h, "w", encoding="utf-8", newline="\n").write("\n".join(h) + "\n")

# ---- C# ------------------------------------------------------------------------------------------------------------
c = []
v = c.append
v("// <auto-generated> gen_harness_bridge.py が EGen の TxnHarnessDBInterface.h から生成した。手で直さない。 </auto-generated>")
v("#nullable enable")
v("namespace Benchmark.TpcE.Core.Harness;")
v("/// <summary>ハーネスの取引(EGenTxnHarness のクラス)。値はブリッジ DLL の取引 ID と同じ。</summary>")
v("public enum HarnessTransaction{")
for index, txn in enumerate(txn_order):
    v("    %s=%d," % (txn, index))
v("}")
v("/// <summary>ハーネスが DB インターフェースを通して呼ぶフレーム。値はブリッジ DLL のフレーム ID と同じ。</summary>")
v("public enum HarnessFrame{")
for fid, txn, name, number, in_type, out_type in frame_table:
    v("    %s%d=%d," % (txn, number, fid))
v("}")
v("/// <summary>フレームごとの入力・出力の構造体名(無ければ null)。</summary>")
v("public static class HarnessFrameInfo{")
v("    public static readonly IReadOnlyList<(HarnessFrame Frame,HarnessTransaction Transaction,int Number,string? Input,string? Output)> All=[")
for fid, txn, name, number, in_type, out_type in frame_table:
    i = "null"
    o = "null"
    if in_type:
        i = '"%s"' % in_type[1:]
    if out_type:
        o = '"%s"' % out_type[1:]
    v("        (HarnessFrame.%s%d,HarnessTransaction.%s,%d,%s,%s)," % (txn, number, txn, number, i, o))
v("    ];")
v("}")
open(out_cs, "w", encoding="utf-8", newline="\n").write("\n".join(c) + "\n")
print("frames: %d, transactions: %d" % (len(frame_table), len(txn_order)))
