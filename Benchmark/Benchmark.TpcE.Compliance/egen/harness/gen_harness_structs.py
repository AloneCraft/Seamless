"""
EGen の TxnHarnessStructs.h から、C# の構造体ラッパー(HarnessStructs.g.cs)を生成する開発用スクリプト。

手順:
  1. ヘッダーを読み、クラスとフィールド(型・名前・配列の次元の式)を取り出す。
  2. 各フィールドの offsetof / sizeof と、配列の次元の値を、実際の C++ コンパイラ(MSVC)に出力させる(LayoutDump.cpp)。
     レイアウトは推測せず、コンパイラの値をそのまま使う。
  3. 実測値から、byte のスパン上でフィールドを読み書きする C# のラッパーを生成する(unsafe を使わない)。

使い方: python gen_harness_structs.py <EGen の展開先> <出力の .cs>
生成物はリポジトリに入れる。EGen を更新したときだけ作り直す。
"""
import os
import re
import subprocess
import sys

egen = sys.argv[1]
output = sys.argv[2]
header = os.path.join(egen, "inc", "TxnHarnessStructs.h")
work = os.path.join(os.environ.get("TEMP", "."), "tpce-harness-layout")
os.makedirs(work, exist_ok=True)

text = open(header, encoding="utf-8", errors="replace").read()
text = re.sub(r"//.*", "", text)
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
# クラスの本体にあるコンストラクターと Clear() を先に除く(中の波括弧がクラスの終端と取り違えられるため)。
text = re.sub(r"#ifdef.*?#endif", "", text, flags=re.S)
text = re.sub(r"inline void Clear\(\)\s*\{[^}]*\}", "", text)

SCALARS = {"double", "INT32", "INT64", "TIdent", "TTrade", "bool", "char", "DB_INDICATOR", "TIMESTAMP_STRUCT", "eMEETradeRequestAction"}

classes = []  # (name, aliases, fields)
for match in re.finditer(r"typedef\s+class\s+(\w+)\s*\{(.*?)\}\s*([^;]*);", text, re.S):
    name, body, tail = match.group(1), match.group(2), match.group(3)
    aliases = [a.strip() for a in tail.split(",") if a.strip() and not a.strip().startswith("*")]
    aliases = [a for a in aliases if a != name]
    body = re.sub(r"#ifdef.*?#endif", "", body, flags=re.S)
    body = re.sub(r"inline void Clear\(\)\s*\{.*?\}", "", body, flags=re.S)
    fields = []
    for raw in body.split(";"):
        line = " ".join(raw.split()).replace("public:", "").strip()
        if not line or "(" in line:
            continue
        m = re.match(r"([\w:]+)\s+(\w+)((?:\[[^\]]+\])*)$", line)
        if not m:
            raise SystemExit("cannot parse field: %s in %s" % (line, name))
        dims = re.findall(r"\[([^\]]+)\]", m.group(3))
        fields.append((m.group(1), m.group(2), dims))
    classes.append((name, aliases, fields))

class_names = {c[0] for c in classes}

# ---- C++ のレイアウト出力 -----------------------------------------------------------------------------------------
cpp = ['#include "TxnHarnessStructs.h"', "#include <cstdio>", "#include <cstddef>", "using namespace TPCE;", "int main(){"]
for name, aliases, fields in classes:
    cpp.append('  printf("CLASS %s %%d\\n",(int)sizeof(%s));' % (name, name))
    for ftype, fname, dims in fields:
        dim_values = " %d" * len(dims)
        dim_args = "".join(",(int)(%s)" % d for d in dims)
        # 出力の形: FIELD <クラス> <フィールド> <型> <offset> <size> <次元の値...>
        cpp.append('  printf("FIELD %s %s %s %%d %%d%s\\n",(int)offsetof(%s,%s),(int)sizeof(((%s*)0)->%s)%s);' % (name, fname, ftype, dim_values, name, fname, name, fname, dim_args))
for scalar in sorted(SCALARS):
    cpp.append('  printf("SIZE %s %%d\\n",(int)sizeof(%s));' % (scalar, scalar))
cpp.append("  return 0; }")
dump_cpp = os.path.join(work, "LayoutDump.cpp")
open(dump_cpp, "w", encoding="utf-8").write("\n".join(cpp))

vcvars = r"C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvars64.bat"
exe = os.path.join(work, "LayoutDump.exe")
command = '"%s" >nul 2>&1 && cl /nologo /utf-8 /EHsc /std:c++14 /FIstdio.h /wd4996 /D_CRT_SECURE_NO_DEPRECATE /DWIN32 /I"%s" /I"%s" /Fo"%s\\\\" /Fe"%s" "%s"' % (
    vcvars, os.path.join(egen, "inc"), os.path.join(egen, "Utilities", "inc"), work, exe, dump_cpp)
# cmd /c は、行頭が引用符で引用符が 3 個以上あると最初と最後の引用符を剥がす。全体をもう一段包んで防ぐ。
result = subprocess.run('cmd /c "' + command + '"', capture_output=True, text=True, errors="replace")
if not os.path.exists(exe):
    sys.stderr.write(result.stdout + result.stderr)
    raise SystemExit("layout dump did not compile")
dump = subprocess.run([exe], capture_output=True, text=True).stdout

sizes = {}
class_sizes = {}
field_info = {}  # (class, field) -> (offset, size, dims)
for line in dump.splitlines():
    parts = line.split()
    if parts[0] == "SIZE":
        sizes[parts[1]] = int(parts[2])
    elif parts[0] == "CLASS":
        class_sizes[parts[1]] = int(parts[2])
        sizes[parts[1]] = int(parts[2])
    elif parts[0] == "FIELD":
        field_info[(parts[1], parts[2])] = (int(parts[4]), int(parts[5]), [int(p) for p in parts[6:]])

# ---- C# の生成 ----------------------------------------------------------------------------------------------------
def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))

def prop_name(name):
    result = pascal(name)
    return result

SCALAR_CS = {"double": "double", "INT32": "int", "INT64": "long", "TIdent": "long", "TTrade": "long", "eMEETradeRequestAction": "int"}

lines = []
w = lines.append
w("// <auto-generated>")
w("// EGen の TxnHarnessStructs.h と、MSVC で実測したレイアウトから gen_harness_structs.py が生成した。手で直さない。")
w("// </auto-generated>")
w("#nullable enable")
w("using System.Runtime.InteropServices;")
w("using System.Text;")
w("namespace Benchmark.TpcE.Core.Harness;")
w("/// <summary>EGen の TIMESTAMP_STRUCT(ODBC と同じ)。</summary>")
w("public readonly record struct EGenTimestamp(short Year,ushort Month,ushort Day,ushort Hour,ushort Minute,ushort Second,uint Fraction){")
w("    public const int Size=%d;" % sizes["TIMESTAMP_STRUCT"])
w("    public bool IsEmpty=>this.Year==0&&this.Month==0&&this.Day==0;")
w("    /// <summary>0001-01-01 からのミリ秒。使わない(年月日が 0 の)値は 0。</summary>")
w("    public long ToMilliseconds(){")
w("        if(this.Year<1||this.Month<1||this.Day<1){")
w("            return 0;")
w("        }")
w("        return TpcETime.FromDateTime(new DateTime(this.Year,this.Month,this.Day,this.Hour,this.Minute,this.Second))+this.Fraction/1_000_000;")
w("    }")
w("    public static EGenTimestamp FromMilliseconds(long milliseconds){")
w("        if(milliseconds<=0){")
w("            return default;")
w("        }")
w("        var value=TpcETime.ToDateTime(milliseconds);")
w("        return new EGenTimestamp((short)value.Year,(ushort)value.Month,(ushort)value.Day,(ushort)value.Hour,(ushort)value.Minute,(ushort)value.Second,(uint)(milliseconds%1000)*1_000_000);")
w("    }")
w("}")
w("/// <summary>固定長の ASCII 文字列(NUL 終端)の読み書き。</summary>")
w("internal static class HarnessText{")
w("    public static string Read(ReadOnlySpan<byte> bytes){")
w("        var length=bytes.IndexOf((byte)0);")
w("        if(length<0){")
w("            length=bytes.Length;")
w("        }")
w("        return Encoding.ASCII.GetString(bytes[..length]);")
w("    }")
w("    public static void Write(Span<byte> bytes,string value){")
w("        bytes.Clear();")
w("        var count=Math.Min(Encoding.ASCII.GetByteCount(value),bytes.Length-1);")
w("        Encoding.ASCII.GetBytes(value.AsSpan(),bytes[..count]);")
w("    }")
w("}")

index = []  # (class, aliases, size)
for name, aliases, fields in classes:
    csname = name[1:] if name.startswith("T") else name
    w("/// <summary>%s(%d バイト)。</summary>" % (name, class_sizes[name]))
    w("public readonly ref struct %s{" % csname)
    w("    private readonly Span<byte> bytes;")
    w("    public %s(Span<byte> bytes){" % csname)
    w("        this.bytes=bytes;")
    w("    }")
    w("    public const int Size=%d;" % class_sizes[name])
    w("    public Span<byte> Bytes=>this.bytes;")
    index.append((csname, aliases, class_sizes[name]))
    for ftype, fname, dims in fields:
        offset, size, dim_values = field_info[(name, fname)]
        p = prop_name(fname)
        if ftype == "char":
            if len(dims) == 0:
                w("    public char %s{get=>(char)bytes[%d];set=>bytes[%d]=(byte)value;}" % (p, offset, offset))
            elif len(dims) == 1:
                w("    public string %s{get=>HarnessText.Read(bytes.Slice(%d,%d));set=>HarnessText.Write(bytes.Slice(%d,%d),value);}" % (p, offset, size, offset, size))
            else:
                inner = dim_values[1]
                w("    public string Get%s(int index)=>HarnessText.Read(bytes.Slice(%d+index*%d,%d));" % (p, offset, inner, inner))
                w("    public void Set%s(int index,string value)=>HarnessText.Write(bytes.Slice(%d+index*%d,%d),value);" % (p, offset, inner, inner))
            continue
        if ftype == "bool":
            if len(dims) == 0:
                w("    public bool %s{get=>bytes[%d]!=0;set=>bytes[%d]=(byte)Convert.ToInt32(value);}" % (p, offset, offset))
            else:
                w("    public bool Get%s(int index)=>bytes[%d+index]!=0;" % (p, offset))
                w("    public void Set%s(int index,bool value)=>bytes[%d+index]=(byte)Convert.ToInt32(value);" % (p, offset))
            continue
        if ftype == "DB_INDICATOR":
            cs = "int"
            if sizes["DB_INDICATOR"] == 2:
                cs = "short"
            element = sizes["DB_INDICATOR"]
        elif ftype == "TIMESTAMP_STRUCT":
            cs = "EGenTimestamp"
            element = sizes["TIMESTAMP_STRUCT"]
        elif ftype in SCALAR_CS:
            cs = SCALAR_CS[ftype]
            element = sizes[ftype]
        elif ftype in class_names:
            cs = ftype[1:]
            element = sizes[ftype]
        else:
            raise SystemExit("unknown type %s in %s" % (ftype, name))
        if ftype in class_names:
            if len(dims) == 0:
                w("    public %s %s=>new(bytes.Slice(%d,%d));" % (cs, p, offset, element))
            else:
                w("    public %s Get%s(int index)=>new(bytes.Slice(%d+index*%d,%d));" % (cs, p, offset, element, element))
                w("    public int %sCount=>%d;" % (p, dim_values[0]))
            continue
        if ftype == "TIMESTAMP_STRUCT":
            read = "new EGenTimestamp(MemoryMarshal.Read<short>(bytes[{o}..]),MemoryMarshal.Read<ushort>(bytes[({o}+2)..]),MemoryMarshal.Read<ushort>(bytes[({o}+4)..]),MemoryMarshal.Read<ushort>(bytes[({o}+6)..]),MemoryMarshal.Read<ushort>(bytes[({o}+8)..]),MemoryMarshal.Read<ushort>(bytes[({o}+10)..]),MemoryMarshal.Read<uint>(bytes[({o}+12)..]))"
            write = "{{short y=value.Year;ushort mo=value.Month;ushort d=value.Day;ushort h=value.Hour;ushort mi=value.Minute;ushort se=value.Second;uint f=value.Fraction;MemoryMarshal.Write(bytes[{o}..],in y);MemoryMarshal.Write(bytes[({o}+2)..],in mo);MemoryMarshal.Write(bytes[({o}+4)..],in d);MemoryMarshal.Write(bytes[({o}+6)..],in h);MemoryMarshal.Write(bytes[({o}+8)..],in mi);MemoryMarshal.Write(bytes[({o}+10)..],in se);MemoryMarshal.Write(bytes[({o}+12)..],in f);}}"
            if len(dims) == 0:
                o = str(offset)
                w("    public EGenTimestamp %s{get=>%s;set%s}" % (p, read.format(o=o), write.format(o=o)))
            else:
                o = "%d+index*%d" % (offset, element)
                w("    public EGenTimestamp Get%s(int index)=>%s;" % (p, read.format(o="("+o+")")))
                w("    public void Set%s(int index,EGenTimestamp value)%s" % (p, write.format(o="("+o+")")))
            continue
        if len(dims) == 0:
            w("    public %s %s{get=>MemoryMarshal.Read<%s>(bytes[%d..]);set=>MemoryMarshal.Write(bytes[%d..],in value);}" % (cs, p, cs, offset, offset))
        else:
            w("    public %s Get%s(int index)=>MemoryMarshal.Read<%s>(bytes[(%d+index*%d)..]);" % (cs, p, cs, offset, element))
            w("    public void Set%s(int index,%s value)=>MemoryMarshal.Write(bytes[(%d+index*%d)..],in value);" % (p, cs, offset, element))
            w("    public int %sCount=>%d;" % (p, dim_values[0]))
    w("}")

w("/// <summary>生成した構造体の名前・別名・大きさ(試験で C++ の実測と照合する)。</summary>")
w("public static class HarnessLayout{")
w("    public static readonly IReadOnlyList<(string Name,string[] Aliases,int Size)> Classes=[")
for csname, aliases, size in index:
    alias_list = ",".join('"%s"' % a for a in aliases)
    w('        ("%s",[%s],%d),' % (csname, alias_list, size))
w("    ];")
w("}")
open(output, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("generated %d structs -> %s" % (len(classes), output))
