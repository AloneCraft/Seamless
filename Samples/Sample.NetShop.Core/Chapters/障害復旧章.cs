using Sample.NetShop.Core.Shop;

namespace Sample.NetShop.Core;

/// <summary>8章: 確定した取引だけが残ること。取引の途中で止まった注文は、開き直すと存在しない。</summary>
public sealed class 障害復旧章:物語の章{
    public override string 題名=>"停電からの復旧";
    public override string 使う機能=>"取引の原子性 / WAL / ストレージ方式の再オープン";
    public override string 説明=>
        "注文の取引を処理している途中で停電が起きたとします。\n"+
        "DB は確定(Commit)した取引をまずログ(WAL)に書いてから表へ反映するので、確定済みの注文は必ず残り、\n"+
        "確定していない注文は開き直しても現れません。ここでは同じアプリの中で DB を閉じて開き直して確かめます。";
    public override string コード=>
        """
        var 前=(商店.注文.LongCount,商店.売上合計().Value);
        using(var 取引=商店.BeginTransaction()){
            商店.注文確定(顧客ID,行一覧,日時);    // 取引の中で注文を登録
            // ここで停電 → Commit されない
        }
        商店を開き直す();                         // 閉じて、もう一度開く
        var 後=(商店.注文.LongCount,商店.売上合計().Value);   // 前と同じ
        """;

    public override async Task 実行Async(章の文脈 文脈){
        // 3章を飛ばして始めても動くよう、空の店なら先に商品と顧客を登録する(登録済みなら何もしない)。
        if(文脈.商店.初期データを登録する()){
            文脈.ログ("この章から始めたので、先に商品と顧客を登録しました。");
        }
        文脈.コードを指す("var 前=");
        var 前の件数=文脈.商店.注文.LongCount;
        var 前の売上=文脈.商店.売上合計().Value;
        this.描く(文脈,前の件数,前の売上,null,null);
        文脈.ログ($"いまの注文 {前の件数:N0} 件、売上 {表示.金額(前の売上)}");
        await 文脈.間を置くAsync();

        文脈.コードを指す("using(var 取引=");
        using(var 取引=文脈.商店.BeginTransaction()){
            文脈.コードを指す("商店.注文確定");
            var 商品=初期データ.商品一覧[3];
            var 結果=文脈.商店.注文確定(初期データ.顧客一覧[0].顧客ID,[new 注文行(商品.商品ID,1)],DateTime.Now).Result;
            文脈.ログ($"取引の中で注文を登録しました(取引の中では {文脈.商店.注文.LongCount:N0} 件に見えます)。成功: {結果.成功か}");
            this.描く(文脈,前の件数,前の売上,文脈.商店.注文.LongCount,文脈.商店.売上合計().Value);
            文脈.コードを指す("ここで停電");
            文脈.ログ("⚡ 停電!Commit される前に止まりました。",ログ種別.失敗);
        }
        await 文脈.間を置くAsync(1.5);

        文脈.コードを指す("商店を開き直す");
        文脈.商店を開き直す();
        文脈.ログ("DB を閉じて、もう一度開きました。");
        await 文脈.間を置くAsync();

        文脈.コードを指す("var 後=");
        var 後の件数=文脈.商店.注文.LongCount;
        var 後の売上=文脈.商店.売上合計().Value;
        this.描く(文脈,前の件数,前の売上,後の件数,後の売上);
        if(後の件数!=前の件数||後の売上!=前の売上){
            throw new InvalidOperationException($"開き直した後の内容が停電前と違います(件数 {前の件数}→{後の件数}、売上 {前の売上}→{後の売上})。");
        }
        文脈.ログ("確定済みの注文はすべて残り、途中の注文は消えています。停電前と同じです。",ログ種別.成功);
        await 文脈.間を置くAsync(2);
    }

    private void 描く(章の文脈 文脈,long 前の件数,long 前の売上,long? 後の件数,long? 後の売上){
        var 件数=new List<棒>{new("停電前",前の件数,棒の色.比較)};
        var 売上=new List<棒>{new("停電前",前の売上/10_000.0,棒の色.比較)};
        if(後の件数 is long 件){
            件数.Add(new("いま",件,棒の色.強調));
        }
        if(後の売上 is long 円){
            売上.Add(new("いま",円/10_000.0,棒の色.強調));
        }
        文脈.棒グラフ("注文の件数","件",件数);
        文脈.棒グラフ("売上合計","万円",売上);
    }
}
