namespace Seamless.Database.Generator;

/// <summary>
/// Manager が管理する登録クエリの入口 <c>Seamless.Management.Generated.QueryEntry.Invoke</c> を作る。
/// プロジェクトの設定に印 <c>SeamlessManagedDatabase=true</c> と、入口の型 <c>SeamlessQueryEntryType</c>・メンバー <c>SeamlessQueryEntryMember</c> があるときだけ働く。
/// 11/15 の決定：SDK でのビルドの付け足しはプロジェクトの設定の印を DB 生成器が見て作る(Manager からのビルドと IDE のビルドで同じ DLL になる)。
/// 入口は公開の static で、型引数が無く、引数がすべて値渡しのメソッドが1つだけであること。
/// 設計：Document/refactoring-designs/20261115-Managerの設計と実装の照合.md の段階7。
/// </summary>
[Generator]
public sealed class ManagedQueryEntryGenerator:IIncrementalGenerator{
    public const string DiagnosticId="SEAMLESSMANAGED002";
    private static readonly DiagnosticDescriptor InvalidEntry=new(DiagnosticId,"登録クエリの入口が無いか一意でない",
        "登録クエリの入口 {0}.{1} は、公開の static で、型引数が無く、引数がすべて値渡しのメソッドを1つだけにしてください。","Seamless.Management",DiagnosticSeverity.Error,true);

    public void Initialize(IncrementalGeneratorInitializationContext context){
        var entry=context.AnalyzerConfigOptionsProvider.Select(static (provider,_)=>{
            var options=provider.GlobalOptions;
            if(!options.TryGetValue("build_property.SeamlessManagedDatabase",out var managed)||!string.Equals(managed?.Trim(),"true",StringComparison.OrdinalIgnoreCase)){return null;}
            options.TryGetValue("build_property.SeamlessQueryEntryType",out var type);options.TryGetValue("build_property.SeamlessQueryEntryMember",out var member);
            if(string.IsNullOrWhiteSpace(type)||string.IsNullOrWhiteSpace(member)){return null;}
            return new EntryName(type!.Trim(),member!.Trim());
        });
        context.RegisterSourceOutput(context.CompilationProvider.Combine(entry),static (production,input)=>{
            if(input.Right is not{} name){return;}
            var methods=input.Left.GetTypeByMetadataName(name.Type)?.GetMembers(name.Member).OfType<IMethodSymbol>()
                .Where(static method=>method.IsStatic&&method.DeclaredAccessibility==Accessibility.Public&&!method.IsGenericMethod&&method.Parameters.All(static parameter=>parameter.RefKind==RefKind.None)).ToArray()??[];
            if(methods.Length!=1){production.ReportDiagnostic(Diagnostic.Create(InvalidEntry,Location.None,name.Type,name.Member));return;}
            production.AddSource("ManagedQueryEntry.g.cs",SourceText.From(Bridge(name.Type,methods[0]),Encoding.UTF8));
        });
    }

    // 内蔵のコンパイル(RuntimeCompiler)が足していた入口と同じ形。戻り値の無い入口は null を返す。
    internal static string Bridge(string entryType,IMethodSymbol method){
        var signature=string.Join(",",method.Parameters.Select(static parameter=>parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)+" @"+parameter.Name));
        var arguments=string.Join(",",method.Parameters.Select(static parameter=>"@"+parameter.Name));
        var call="global::"+entryType+".@"+method.Name+"("+arguments+")";
        var resultType=method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);var body="return "+call+";";
        if(method.ReturnsVoid){resultType="object";body=call+";return null!;";}
        return "// <auto-generated/>\nnamespace Seamless.Management.Generated{public static class QueryEntry{public static "+resultType+" Invoke("+signature+"){"+body+"}}}";
    }

    private sealed record EntryName(string Type,string Member);
}
