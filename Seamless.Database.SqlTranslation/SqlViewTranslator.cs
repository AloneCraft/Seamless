using System.Text;
using Microsoft.SqlServer.TransactSql.ScriptDom;
namespace Seamless.Database.SqlTranslation;
/// <summary>訳したビューの列。</summary>
public sealed record ViewColumn(string Name,string CSharpName,SqlTypeDescriptor Type,string CSharpType);
/// <summary>
/// 1つのビューを訳した結果。訳せたときは、行の型(<see cref="RowTypeSource"/>)と、
/// 読み取りの入口への拡張プロパティ(<see cref="MemberSource"/>)を持つ。訳せなければ診断だけを持つ。
/// </summary>
public sealed record ViewTranslation(string Schema,string Name,string? RowType,string? RowTypeSource,string? MemberSource,IReadOnlyList<ViewColumn> Columns,IReadOnlyList<TranslationDiagnostic> Diagnostics){
    /// <summary>訳せたか(未対応の診断が無いか)。</summary>
    public bool Succeeded=>this.MemberSource is not null&&this.Diagnostics.All(static diagnostic=>diagnostic.Severity!=TranslationSeverity.Unsupported);
}
/// <summary>
/// T-SQL のビューの定義(CREATE VIEW)を、ISet を返す読み取りの入口への拡張プロパティへ訳す。
/// 出力は FLinq が呼び出し側へ展開できる形(Seamless.Linq.Set の演算と、値の関数の部品の呼び出し)だけにする。
/// </summary>
public sealed class SqlViewTranslator(TranslationCatalog catalog){
    private readonly TranslationCatalog catalog=catalog;
    /// <summary>ビューを1つ訳す。</summary>
    public ViewTranslation Translate(string schema,string name,string definition){
        var diagnostics=new List<TranslationDiagnostic>();
        try{
            var (query,columnNames,xmlNamespaces)=Parse(definition);
            var binder=new SqlBinder(this.catalog,xmlNamespaces);
            var bound=binder.BindQuery(query,null);
            bound=binder.Unify(bound);
            diagnostics.AddRange(binder.Warnings);
            var items=bound.Items;
            if(columnNames is not null){
                if(columnNames.Count!=items.Count){
                    throw new TranslationUnsupportedException("SQLT130","ビューの列の名前の数が、SELECT の列の数と違う(本物ではエラー 8159)。",1,1);
                }
            }
            // 名前は取込の生成器と同じ規則で付ける。目録にこのビューがあれば、その名前と行の型を使う。
            var schemaName=this.catalog.SchemaIdentifier(schema);
            var typeName=CSharpNames.Identifier(name);
            var rowType=$"global::{this.catalog.RootNamespace}.Views.{schemaName}.{typeName}";
            if(this.catalog.Find(schema,name) is{IsView:true} known){
                typeName=known.Access[(known.Access.LastIndexOf('.')+1)..];
                rowType=known.RowType;
            }
            var names=new CSharpNameScope();
            names.Reserve(typeName);
            var columns=new List<ViewColumn>();
            for(var index=0;index<items.Count;index++){
                var columnName=columnNames?[index]??items[index].Name;
                if(columnName.Length==0){
                    throw new TranslationUnsupportedException("SQLT131",$"{index+1}番目の列に名前が無い(本物ではエラー 4511)。",1,1);
                }
                var unique=names.Get(columnName);
                var type=items[index].Expression.Type;
                if(SqlTypeRules.IsNull(type)){
                    type=SqlTypeRules.Int;
                }
                columns.Add(new(columnName,unique,type,CSharpEmitter.OutputType(type)));
            }
            var rowSource=$"public readonly record struct {typeName}({string.Join(",",columns.Select(static column=>$"{column.CSharpType} {column.CSharpName}"))});";
            var expression=new CSharpEmitter().Query(bound,rowType,columns.Select(static column=>column.Type).ToList());
            var member=$"public global::Seamless.Collections.ISet<{rowType}> {typeName}=>{expression};";
            return new(schema,name,rowType,rowSource,member,columns,diagnostics);
        }catch(TranslationUnsupportedException error){
            diagnostics.Add(error.Diagnostic);
            return new(schema,name,null,null,null,[],diagnostics);
        }
    }
    /// <summary>訳したビューをまとめて1つの C# ファイルにする。訳せなかったものは含めない。</summary>
    public string SourceFile(IEnumerable<ViewTranslation> translations){
        var succeeded=translations.Where(static translation=>translation.Succeeded).ToList();
        var builder=new StringBuilder();
        builder.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS8981\n");
        foreach(var schema in succeeded.GroupBy(translation=>this.catalog.SchemaIdentifier(translation.Schema))){
            builder.Append($"\nnamespace {this.catalog.RootNamespace}.Views.{schema.Key}{{\n");
            foreach(var translation in schema){
                builder.Append("    ").Append(translation.RowTypeSource).Append('\n');
            }
            builder.Append("}\n");
        }
        builder.Append($"\nnamespace {this.catalog.RootNamespace}.Queries{{\n    using global::Seamless.Linq;\n");
        foreach(var schema in succeeded.GroupBy(static translation=>translation.Schema,StringComparer.OrdinalIgnoreCase)){
            builder.Append($"    public static partial class {this.catalog.SchemaIdentifier(schema.Key)}Views{{\n");
            builder.Append($"        extension({this.catalog.ReaderType(schema.Key)} q){{\n");
            foreach(var translation in schema){
                builder.Append("            ").Append(translation.MemberSource).Append('\n');
            }
            builder.Append("        }\n    }\n");
        }
        builder.Append("}\n");
        return builder.ToString();
    }
    private static (QueryExpression Query,IList<string>? Columns,string XmlNamespaces) Parse(string definition){
        var parser=new TSql170Parser(true);
        var fragment=parser.Parse(new StringReader(definition),out var errors);
        if(errors.Count>0){
            var error=errors[0];
            throw new TranslationUnsupportedException("SQLT002",$"構文の誤り: {error.Message}",error.Line,error.Column);
        }
        if(fragment is not TSqlScript script||script.Batches.Count!=1||script.Batches[0].Statements.Count!=1){
            throw new TranslationUnsupportedException("SQLT003","CREATE VIEW の文が1つではない。",1,1);
        }
        var statement=script.Batches[0].Statements[0];
        SelectStatement select;
        IList<string>? columns=null;
        if(statement is ViewStatementBody view){
            select=view.SelectStatement;
            if(view.Columns.Count>0){
                columns=view.Columns.Select(static column=>column.Value).ToList();
            }
        }else if(statement is SelectStatement plain){
            select=plain;
        }else{
            throw SqlBinder.Unsupported(statement,"SQLT003",statement.GetType().Name);
        }
        var namespaces="";
        if(select.WithCtesAndXmlNamespaces is{} with){
            if(with.CommonTableExpressions.Count>0||with.ChangeTrackingContext is not null){
                throw SqlBinder.Unsupported(select,"SQLT004","WITH の共通テーブル式(段階3)");
            }
            // WITH XMLNAMESPACES は、xml のメソッドの XQuery の先頭の宣言にする。
            if(with.XmlNamespaces is{} xml){
                var builder=new System.Text.StringBuilder();
                foreach(var element in xml.XmlNamespacesElements){
                    switch(element){
                        case XmlNamespacesAliasElement alias:
                            builder.Append($"declare namespace {alias.Identifier.Value}=\"{alias.String.Value}\";");
                            break;
                        case XmlNamespacesDefaultElement @default:
                            builder.Append($"declare default element namespace \"{@default.String.Value}\";");
                            break;
                    }
                }
                namespaces=builder.ToString();
            }
        }
        return (select.QueryExpression,columns,namespaces);
    }
}
