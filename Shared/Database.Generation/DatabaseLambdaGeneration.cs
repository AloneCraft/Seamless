using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Threading;

namespace Shared.Database.Generation;

internal sealed class DatabaseLambdaGeneration:IIncrementalGenerator{
    private static readonly DiagnosticDescriptor Unsupported=new("DBGEN006","Unsupported server lambda","{0}","Seamless.Database",DiagnosticSeverity.Error,true);

    public void Initialize(IncrementalGeneratorInitializationContext context){
        // FLinqのpost-initが存在しないクライアント専用プロジェクトでもinterceptorを生成する。
        context.RegisterSourceOutput(context.CompilationProvider,static(output,compilation)=>{
            var attribute=compilation.GetTypeByMetadataName("System.Runtime.CompilerServices.InterceptsLocationAttribute");
            if(attribute is not null&&(SymbolEqualityComparer.Default.Equals(attribute.ContainingAssembly,compilation.Assembly)||attribute.DeclaredAccessibility==Accessibility.Public)){return;}
            output.AddSource("Seamless.Lambda.InterceptsLocationAttribute.g.cs",SourceText.From("""
                // <auto-generated/>
                namespace System.Runtime.CompilerServices{
                    [global::System.AttributeUsage(global::System.AttributeTargets.Method,AllowMultiple=true)]
                    internal sealed class InterceptsLocationAttribute:global::System.Attribute{
                        public InterceptsLocationAttribute(int version,string data){}
                    }
                }
                """,Encoding.UTF8));
        });
        var calls=context.SyntaxProvider.CreateSyntaxProvider(static(node,_)=>node is InvocationExpressionSyntax,
            static(syntax,cancellation)=>Create(syntax,cancellation)).Where(static target=>target is not null);
        context.RegisterSourceOutput(calls,static(output,target)=>{
            if(target!.Error is{} error){output.ReportDiagnostic(Diagnostic.Create(Unsupported,target.Location,error));}
            else{output.AddSource("Seamless.Lambda."+target.Position+"."+StableName(target.Path)+".g.cs",SourceText.From(target.Source!,Encoding.UTF8));}
        });
    }

    private static Target? Create(GeneratorSyntaxContext context,CancellationToken cancellation){
        var invocation=(InvocationExpressionSyntax)context.Node;
        if(context.SemanticModel.GetSymbolInfo(invocation,cancellation).Symbol is not IMethodSymbol method
            ||method.ContainingType.OriginalDefinition.ToDisplayString()!="Seamless.Database.Client.NativeLambdaClient<TDatabase>"
            ||method.Name is not("DefineQuery" or "ExecuteAsync")){return null;}
        try{
            if(invocation.ArgumentList.Arguments.Any(static argument=>argument.NameColon is not null)){throw new NotSupportedException("ラムダ入口の引数は位置で指定してください。");}
            var index=0;if(method.Name=="ExecuteAsync"){index=1;}
            if(invocation.ArgumentList.Arguments.Count<=index||invocation.ArgumentList.Arguments[index].Expression is not LambdaExpressionSyntax lambda){throw new NotSupportedException("呼出位置にラムダを直接記述してください。定義済みのClientQueryはそのまま再利用できます。");}
            if(method.TypeArguments.Length!=2||method.TypeArguments.Any(static type=>type is INamedTypeSymbol{IsAnonymousType:true}||type.TypeKind is TypeKind.Error or TypeKind.TypeParameter)){throw new NotSupportedException("引数と結果には公開された具体的な通信型を指定してください。");}
            var builder=new ProgramBuilder(context.SemanticModel);
            var parameters=Parameters(lambda);
            if(parameters.Length!=2){throw new NotSupportedException("ラムダはDBと型付き引数の二つのパラメーターで記述してください。");}
            foreach(var parameter in parameters){builder.Parameter(parameter);}
            var body=builder.Body(lambda.Body);
            var location=context.SemanticModel.GetInterceptableLocation(invocation,cancellation)??throw new NotSupportedException("この呼出位置をinterceptできません。");
            var attribute=Microsoft.CodeAnalysis.CSharp.CSharpExtensions.GetInterceptsLocationAttributeSyntax(location);
            var database=method.ContainingType.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var arguments=method.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var result=method.TypeArguments[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var client=$"global::Seamless.Database.Client.NativeLambdaClient<{database}>";
            var query=$"global::System.Func<{database},{arguments},{result}>";
            var suffix=StableName(invocation.SyntaxTree.FilePath)+"_"+invocation.SpanStart;
            var signature=$"this {client} client,{query} query";
            var returnType=$"global::Seamless.Database.Client.ClientQuery<{arguments},{result}>";
            var execution=$"client.CreateGeneratedQuery<{arguments},{result}>({body})";
            if(method.Name=="ExecuteAsync"){
                signature=$"this {client} client,{arguments} arguments,{query} query,global::System.Threading.CancellationToken cancellationToken=default";
                returnType=$"global::System.Threading.Tasks.Task<{result}>";
                execution+=".ExecuteAsync(arguments,cancellationToken)";
            }
            var source=$"// <auto-generated/>\n#nullable enable\nnamespace Intercept{{internal static class Lambda_{suffix}{{{attribute}\npublic static {returnType} Invoke({signature})=>{execution};}}}}";
            return new(invocation.GetLocation(),invocation.SpanStart,invocation.SyntaxTree.FilePath,source,null);
        }catch(NotSupportedException error){return new(invocation.GetLocation(),invocation.SpanStart,invocation.SyntaxTree.FilePath,null,error.Message);}
    }

    private static ParameterSyntax[] Parameters(LambdaExpressionSyntax lambda){
        if(lambda is ParenthesizedLambdaExpressionSyntax parenthesized){return parenthesized.ParameterList.Parameters.ToArray();}
        return[((SimpleLambdaExpressionSyntax)lambda).Parameter];
    }
    private static string StableName(string path){unchecked{uint hash=2166136261;foreach(var item in path){hash=(hash^item)*16777619;}return hash.ToString("x8");}}
    private sealed record Target(Location Location,int Position,string Path,string? Source,string? Error);

    private sealed class ProgramBuilder(SemanticModel model){
        private readonly Dictionary<ISymbol,string> names=new(SymbolEqualityComparer.Default);
        private int nextParameter;
        private int nextLocal;
        public void Parameter(ParameterSyntax parameter){var symbol=model.GetDeclaredSymbol(parameter)??throw UnsupportedNode(parameter);this.names.Add(symbol,"p"+this.nextParameter++);}
        public string Body(CSharpSyntaxNode body){
            if(body is BlockSyntax block){return this.Statement(block);}
            return Node("Block",null,Node("Return",null,this.Expression((ExpressionSyntax)body)));
        }
        private string Statement(StatementSyntax statement){
            switch(statement){
                case BlockSyntax block:return Node("Block",null,block.Statements.Select(this.Statement).ToArray());
                case ReturnStatementSyntax{Expression:{} expression}:return Node("Return",null,this.Expression(expression));
                case ExpressionStatementSyntax expression:return Node("Expression",null,this.Expression(expression.Expression));
                case LocalDeclarationStatementSyntax local:{
                    var nodes=new List<string>();
                    foreach(var variable in local.Declaration.Variables){
                        if(variable.Initializer is null){throw UnsupportedNode(variable);}
                        var symbol=model.GetDeclaredSymbol(variable)??throw UnsupportedNode(variable);var name="v"+this.nextLocal++;
                        var initializer=this.Expression(variable.Initializer.Value);this.names.Add(symbol,name);nodes.Add(Node("Local",name,initializer));
                    }
                    return Node("Declarations",null,nodes.ToArray());
                }
                case IfStatementSyntax conditional:{
                    var nodes=new List<string>{this.Expression(conditional.Condition),this.Statement(conditional.Statement)};
                    if(conditional.Else is{} otherwise){nodes.Add(this.Statement(otherwise.Statement));}
                    return Node("If",null,nodes.ToArray());
                }
                case ForEachStatementSyntax loop:{
                    var sequence=this.Expression(loop.Expression);var symbol=model.GetDeclaredSymbol(loop)??throw UnsupportedNode(loop);var name="v"+this.nextLocal++;this.names.Add(symbol,name);
                    return Node("ForEach",name,sequence,this.Statement(loop.Statement));
                }
                case ThrowStatementSyntax{Expression:ObjectCreationExpressionSyntax creation} when model.GetTypeInfo(creation).Type?.ToDisplayString()=="System.InvalidOperationException"&&creation.ArgumentList?.Arguments.Count==1:
                    return Node("Throw",null,this.Expression(creation.ArgumentList.Arguments[0].Expression));
                default:throw UnsupportedNode(statement);
            }
        }

        private string Expression(ExpressionSyntax expression){
            if(expression is ParenthesizedExpressionSyntax parenthesized){return this.Expression(parenthesized.Expression);}
            var constant=model.GetConstantValue(expression);
            if(constant.HasValue){
                if(constant.Value is null){return Node("Null");}
                var type=model.GetTypeInfo(expression).Type;
                if(type?.TypeKind==TypeKind.Enum){return Node("Enum",TypeName(type),Node("Literal",Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(constant.Value,true,false)));}
                return Node("Literal",Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(constant.Value,true,false));
            }
            switch(expression){
                case IdentifierNameSyntax identifier:{
                    var symbol=model.GetSymbolInfo(identifier).Symbol??throw UnsupportedNode(identifier);
                    if(this.names.TryGetValue(symbol,out var name)){return Node("Variable",name);}
                    if(symbol is INamedTypeSymbol type){return Node("Type",TypeName(type));}
                    throw new NotSupportedException("ラムダ外の値は捕捉せず、型付き引数から渡してください: "+identifier.Identifier.ValueText);
                }
                case MemberAccessExpressionSyntax member:return Node("Member",MemberName(member),this.Expression(member.Expression));
                case InvocationExpressionSyntax invocation:return this.Call(invocation);
                case ObjectCreationExpressionSyntax creation when creation.ArgumentList is{} arguments&&creation.Initializer is null:
                    return Node("New",TypeName(model.GetTypeInfo(creation).Type??throw UnsupportedNode(creation)),arguments.Arguments.Select(argument=>this.Expression(argument.Expression)).ToArray());
                case ImplicitObjectCreationExpressionSyntax creation when creation.Initializer is null:
                    return Node("New",TypeName(model.GetTypeInfo(creation).Type??throw UnsupportedNode(creation)),creation.ArgumentList.Arguments.Select(argument=>this.Expression(argument.Expression)).ToArray());
                case BinaryExpressionSyntax binary:return Node("Binary",binary.OperatorToken.ValueText,this.Expression(binary.Left),this.Expression(binary.Right));
                case PrefixUnaryExpressionSyntax unary:return Node("Unary",unary.OperatorToken.ValueText,this.Expression(unary.Operand));
                case PostfixUnaryExpressionSyntax unary:return Node("Postfix",unary.OperatorToken.ValueText,this.Expression(unary.Operand));
                case AssignmentExpressionSyntax assignment:return Node("Assign",assignment.OperatorToken.ValueText,this.Expression(assignment.Left),this.Expression(assignment.Right));
                case ConditionalExpressionSyntax conditional:return Node("Conditional",null,this.Expression(conditional.Condition),this.Expression(conditional.WhenTrue),this.Expression(conditional.WhenFalse));
                case ElementAccessExpressionSyntax indexer:return Node("Index",null,new[]{this.Expression(indexer.Expression)}.Concat(indexer.ArgumentList.Arguments.Select(argument=>this.Expression(argument.Expression))).ToArray());
                case CastExpressionSyntax cast:return Node("Convert",TypeName(model.GetTypeInfo(cast.Type).Type??throw UnsupportedNode(cast)),this.Expression(cast.Expression));
                case LambdaExpressionSyntax lambda:{
                    var parameters=Parameters(lambda);var names=new List<string>();
                    foreach(var parameter in parameters){this.Parameter(parameter);names.Add(this.names[model.GetDeclaredSymbol(parameter)!]);}
                    return Node("Lambda",string.Join(",",names),this.Body(lambda.Body));
                }
                default:throw UnsupportedNode(expression);
            }
        }

        private string Call(InvocationExpressionSyntax invocation){
            var method=model.GetSymbolInfo(invocation).Symbol as IMethodSymbol??throw UnsupportedNode(invocation);
            var definition=method.ReducedFrom??method;
            var owner=definition.ContainingType.OriginalDefinition.ToDisplayString();
            var arguments=invocation.ArgumentList.Arguments.Select(argument=>this.Expression(argument.Expression)).ToList();
            if(owner=="System.Linq.Enumerable"){
                if(method.ReducedFrom is not null){arguments.Insert(0,this.Expression(((MemberAccessExpressionSyntax)invocation.Expression).Expression));}
                return Node("Linq",method.Name,arguments.ToArray());
            }
            if(owner=="Seamless.Database.Client.NativeTable<TKey, TRecord>"||owner=="string"){
                if(invocation.Expression is not MemberAccessExpressionSyntax member){throw UnsupportedNode(invocation);}
                arguments.Insert(0,this.Expression(member.Expression));return Node("Call",method.Name,arguments.ToArray());
            }
            throw new NotSupportedException("サーバーラムダから呼び出せないメソッドです: "+method.ToDisplayString());
        }
        private string MemberName(MemberAccessExpressionSyntax member){var symbol=model.GetSymbolInfo(member).Symbol??throw UnsupportedNode(member);if(symbol is not(IPropertySymbol or IFieldSymbol)){throw UnsupportedNode(member);}return symbol.Name;}
        private static string TypeName(ITypeSymbol type)=>type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::","");
        private static NotSupportedException UnsupportedNode(SyntaxNode node)=>new("未対応のサーバーラムダ構文です: "+node.Kind());
        private static string Node(string kind,string? text=null,params string[] children){
            var value="null";if(text is not null){value=Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text,true);}
            return "new global::Seamless.Database.Client.NativeLambdaNode("+Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(kind,true)+","+value+",new global::Seamless.Database.Client.NativeLambdaNode[]{"+string.Join(",",children)+"})";
        }
    }
}
