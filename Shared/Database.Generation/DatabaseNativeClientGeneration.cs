using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Shared.Database.Generation;

/// <summary>公開インターフェースから事前生成メソッドの Graph 通信とサーバー入口を生成する。</summary>
internal sealed class DatabaseNativeClientGeneration:IIncrementalGenerator{
    private static readonly DiagnosticDescriptor Unsupported=new("DBGEN004","Native client contract","{0}","Seamless.Database",DiagnosticSeverity.Error,true);
    private static readonly DiagnosticDescriptor InvalidServer=new("DBGEN005","Native server binding","{0}","Seamless.Database",DiagnosticSeverity.Error,true);

    public void Initialize(IncrementalGeneratorInitializationContext context){
        var markers=context.SyntaxProvider.CreateSyntaxProvider(
            static(node,_)=>node is ClassDeclarationSyntax{Identifier.ValueText:"DatabaseGenerator"},
            static(syntax,_)=>syntax.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)syntax.Node) as INamedTypeSymbol)
            .Where(static marker=>marker is not null).Collect().Combine(context.CompilationProvider);
        context.RegisterSourceOutput(markers,static(output,input)=>Generate(output,input.Left,input.Right));
    }

    private static void Generate(SourceProductionContext context,ImmutableArray<INamedTypeSymbol?> markers,Compilation compilation){
        foreach(var marker in markers.Where(static marker=>marker is not null).Select(static marker=>marker!).Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)){
            var contractName=Text(marker,"ClientContract");
            if(contractName is null){continue;}
            var contract=compilation.GetTypeByMetadataName(contractName);
            var module=Text(marker,"ClientModule");var database=Text(marker,"ClientDatabase");
            if(contract is not{TypeKind:TypeKind.Interface,Arity:0}||module is null||database is null||marker.ContainingNamespace.IsGlobalNamespace){
                context.ReportDiagnostic(Diagnostic.Create(Unsupported,marker.Locations.FirstOrDefault(),"ClientContract、ClientModule、ClientDatabaseと公開インターフェースを指定してください。"));
                continue;
            }
            var methods=contract.GetMembers().OfType<IMethodSymbol>().ToArray();
            if(contract.Interfaces.Length!=0||methods.Length==0||methods.Select(static method=>method.Name).Distinct(StringComparer.Ordinal).Count()!=methods.Length||contract.GetMembers().Any(static member=>member is not IMethodSymbol)||methods.Any(static method=>!Supported(method))){
                context.ReportDiagnostic(Diagnostic.Create(Unsupported,marker.Locations.FirstOrDefault(),"Nativeの生成対象は、型付き引数一つと同期の戻り値を持つ非genericメソッドです。"));
                continue;
            }
            string? serverFactory=null;
            if(Text(marker,"ServerImplementation") is{} implementationName){
                var implementation=compilation.GetTypeByMetadataName(implementationName);
                if(implementation is not{TypeKind:TypeKind.Class,IsAbstract:false,IsGenericType:false}||!compilation.IsSymbolAccessibleWithin(implementation,marker.ContainingAssembly)
                    ||!implementation.AllInterfaces.Contains(contract,SymbolEqualityComparer.Default)){
                    context.ReportDiagnostic(Diagnostic.Create(InvalidServer,marker.Locations.FirstOrDefault(),"ServerImplementationには公開契約を実装するアクセス可能な非generic具象クラスを指定してください。"));
                    continue;
                }
                var constructors=implementation.InstanceConstructors.Where(constructor=>constructor.Parameters.Length==1&&constructor.Parameters[0].RefKind==RefKind.None
                    &&compilation.IsSymbolAccessibleWithin(constructor,marker.ContainingAssembly)&&ServerArgument(constructor.Parameters[0].Type) is not null).ToArray();
                if(constructors.Length!=1){
                    context.ReportDiagnostic(Diagnostic.Create(InvalidServer,marker.Locations.FirstOrDefault(),"ServerImplementationにはINativeQueryContextまたはDatabaseContainerを一つ受け取るアクセス可能なコンストラクターが一つ必要です。"));
                    continue;
                }
                serverFactory="static context=>new "+implementation.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)+"("+ServerArgument(constructors[0].Parameters[0].Type)+")";
            }
            var namespaceName=marker.ContainingNamespace.ToDisplayString();
            var contractType=contract.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var className=contract.Name+"Client";
            if(contract.Name.Length>1&&contract.Name[0]=='I'&&char.IsUpper(contract.Name[1])){className=contract.Name.Substring(1)+"Client";}
            var source=new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            source.AppendLine($"namespace {namespaceName};");
            source.AppendLine($"public sealed partial class {className}{{");
            source.AppendLine("    private readonly global::Seamless.Database.Client.NativeQueryClient? connection;");
            source.AppendLine("    private readonly global::Seamless.Database.Client.NativeTransaction? transaction;");
            source.AppendLine("    private readonly string schemaFingerprint;");
            source.AppendLine($"    public {className}(global::Seamless.Database.Client.NativeQueryClient connection,string schemaFingerprint){{");
            source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(connection);global::System.ArgumentException.ThrowIfNullOrWhiteSpace(schemaFingerprint);");
            source.AppendLine("        this.connection=connection;this.schemaFingerprint=schemaFingerprint;");
            source.AppendLine("    }");
            source.AppendLine($"    public {className}(global::Seamless.Database.Client.NativeTransaction transaction,string schemaFingerprint){{");
            source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(transaction);global::System.ArgumentException.ThrowIfNullOrWhiteSpace(schemaFingerprint);");
            source.AppendLine("        this.transaction=transaction;this.schemaFingerprint=schemaFingerprint;");
            source.AppendLine("    }");
            foreach(var method in methods){
                var argument=method.Parameters[0];var element=Element(method.ReturnType);var result=element??method.ReturnType;
                var argumentType=argument.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);var resultType=result.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var returnType="global::System.Threading.Tasks.Task<"+resultType+">";var invoke="ExecuteRecordScalarAsync";
                if(element is not null){returnType="global::Seamless.Database.Client.NativeResultStream<"+resultType+">";invoke="QueryRecordsStream";}
                source.AppendLine($"    public {returnType} @{method.Name}Async({argumentType} @{argument.Name},global::System.Threading.CancellationToken cancellationToken=default){{");
                source.AppendLine($"        if(this.transaction is not null){{return this.transaction.{invoke}<{argumentType},{resultType},{contractType}>({Literal(module)},{Literal(method.Name)},this.schemaFingerprint,@{argument.Name},cancellationToken);}}");
                source.AppendLine($"        return this.connection!.{invoke}<{argumentType},{resultType},{contractType}>({Literal(module)},{Literal(method.Name)},{Literal(database)},this.schemaFingerprint,@{argument.Name},cancellationToken);");
                source.AppendLine("    }");
            }
            source.AppendLine("}");
            var moduleName=className.Substring(0,className.Length-"Client".Length)+"Module";
            source.AppendLine($"public sealed class {moduleName}:global::Seamless.Database.Client.INativeGeneratedQueryModule{{");
            source.AppendLine($"    private readonly global::System.Func<global::Seamless.Database.Client.INativeQueryContext,{contractType}> factory;");
            if(serverFactory is not null){source.AppendLine($"    public {moduleName}():this({serverFactory}){{}}");}
            source.AppendLine($"    public {moduleName}(global::System.Func<global::Seamless.Database.Client.INativeQueryContext,{contractType}> factory){{global::System.ArgumentNullException.ThrowIfNull(factory);this.factory=factory;}}");
            source.AppendLine($"    public string ModuleId=>{Literal(module)};");
            source.AppendLine($"    public string DatabaseName=>{Literal(database)};");
            source.AppendLine("    public global::System.Collections.Generic.IReadOnlyList<global::Seamless.Database.Client.NativeQueryDefinition> Describe(string schemaFingerprint){");
            source.AppendLine("        global::System.ArgumentException.ThrowIfNullOrWhiteSpace(schemaFingerprint);");
            source.AppendLine("        // [取引/契約] 読取り専用の証明が未接続のため更新可能として登録する。");
            source.AppendLine("        return [");
            foreach(var method in methods){source.AppendLine($"            this.GetContract({Literal(method.Name)}).Define({Literal(method.Name)},{Literal(database)},schemaFingerprint,false),");}
            source.AppendLine("        ];");source.AppendLine("    }");
            source.AppendLine("    public global::Seamless.Database.Client.NativeRecordQueryContract GetContract(string queryId){");
            source.AppendLine("        switch(queryId){");
            foreach(var method in methods){
                var argumentType=method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);var resultType=(Element(method.ReturnType)??method.ReturnType).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                source.AppendLine($"            case {Literal(method.Name)}:return global::Seamless.Database.Client.NativeRecordQueryContract.For<{argumentType},{resultType},{contractType}>();");
            }
            source.AppendLine("            default:throw new global::System.InvalidOperationException(\"Unknown generated native query.\");");
            source.AppendLine("        }");source.AppendLine("    }");
            source.AppendLine("    public global::System.Collections.Generic.IEnumerable<byte[]> Execute(string queryId,global::System.ReadOnlyMemory<byte> arguments,global::Seamless.Database.Client.INativeQueryContext context){");
            source.AppendLine("        context.CancellationToken.ThrowIfCancellationRequested();");source.AppendLine("        switch(queryId){");
            foreach(var method in methods){
                var argumentType=method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);var element=Element(method.ReturnType);var resultType=(element??method.ReturnType).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                source.AppendLine($"            case {Literal(method.Name)}:{{");
                source.AppendLine($"                using var input=global::Seamless.Database.Client.NativeRecordCodec<{argumentType}>.DeserializeOwned(arguments.Span,context.Budget,context.CancellationToken);");
                source.AppendLine("                var implementation=this.factory(context)??throw new global::System.InvalidOperationException(\"The native query factory returned null.\");");
                if(element is not null){
                    source.AppendLine($"                foreach(var row in implementation.@{method.Name}(input.Value)){{");
                    source.AppendLine("                    context.CancellationToken.ThrowIfCancellationRequested();");
                    source.AppendLine($"                    using var output=global::Seamless.Database.Client.NativeRecordCodec<{resultType}>.SerializeOwned(row,context.Budget,context.CancellationToken);");
                    source.AppendLine("                    yield return output.Value;");
                    source.AppendLine("                }");
                }else{
                    source.AppendLine($"                using var output=global::Seamless.Database.Client.NativeRecordCodec<{resultType}>.SerializeOwned(implementation.@{method.Name}(input.Value),context.Budget,context.CancellationToken);");
                    source.AppendLine("                yield return output.Value;");
                }
                source.AppendLine("                yield break;");source.AppendLine("            }");
            }
            source.AppendLine("            default:throw new global::System.InvalidOperationException(\"Unknown generated native query.\");");
            source.AppendLine("        }");source.AppendLine("    }");source.AppendLine("}");
            context.AddSource(namespaceName+".NativeClient.g.cs",SourceText.From(source.ToString(),Encoding.UTF8));
        }
    }

    private static bool Supported(IMethodSymbol method)=>method.MethodKind==MethodKind.Ordinary&&!method.IsStatic&&!method.IsGenericMethod
        &&method.Parameters.Length==1&&method.Parameters[0].RefKind==RefKind.None&&!method.ReturnsByRef&&!method.ReturnsByRefReadonly
        &&method.ReturnType.SpecialType!=SpecialType.System_Void&&!method.ReturnType.IsRefLikeType
        &&method.ReturnType.ContainingNamespace?.ToDisplayString()!="System.Threading.Tasks"
        &&!(method.ReturnType is INamedTypeSymbol asyncType&&asyncType.OriginalDefinition.ToDisplayString()=="System.Collections.Generic.IAsyncEnumerable<T>");
    private static string? ServerArgument(ITypeSymbol type){
        if(type.ToDisplayString()=="Seamless.Database.Client.INativeQueryContext"){return "context";}
        for(var current=type as INamedTypeSymbol;current is not null;current=current.BaseType){
            if(current.ToDisplayString()=="Seamless.Database.DatabaseContainer"){return "("+type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)+")context.Database";}
        }
        return null;
    }
    private static ITypeSymbol? Element(ITypeSymbol type){
        if(type.SpecialType==SpecialType.System_String){return null;}
        if(type is IArrayTypeSymbol array){return array.ElementType;}
        if(type is not INamedTypeSymbol named){return null;}
        if(named.OriginalDefinition.ToDisplayString()=="System.Collections.Generic.IEnumerable<T>"){return named.TypeArguments[0];}
        return named.AllInterfaces.FirstOrDefault(static item=>item.OriginalDefinition.ToDisplayString()=="System.Collections.Generic.IEnumerable<T>")?.TypeArguments[0];
    }
    private static string? Text(INamedTypeSymbol marker,string name)=>marker.GetMembers(name).OfType<IFieldSymbol>().FirstOrDefault(static field=>field.IsConst)?.ConstantValue as string;
    private static string Literal(string value)=>Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value,true);
}
