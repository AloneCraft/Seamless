using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Shared.Database.Generation;

/// <summary>共有する公開インターフェースから既存Native v1の型付き呼び出しを生成する。</summary>
internal sealed class DatabaseNativeClientGeneration:IIncrementalGenerator{
    private static readonly DiagnosticDescriptor Unsupported=new("DBGEN004","Native client contract","{0}","Seamless.Database",DiagnosticSeverity.Error,true);

    public void Initialize(IncrementalGeneratorInitializationContext context){
        var markers=context.SyntaxProvider.CreateSyntaxProvider(
            static(node,_)=>node is ClassDeclarationSyntax{Identifier.ValueText:"DatabaseGenerator"},
            static(syntax,_)=>syntax.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)syntax.Node) as INamedTypeSymbol)
            .Where(static marker=>marker is not null).Collect().Combine(context.CompilationProvider);
        context.RegisterSourceOutput(markers,static(output,input)=>Generate(output,input.Left,input.Right));
    }

    private static void Generate(SourceProductionContext context,ImmutableArray<INamedTypeSymbol?> markers,Compilation compilation){
        foreach(var marker in markers.Where(static marker=>marker is not null).Select(static marker=>marker!).Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)){
            var contractName=Text(marker,"ClientContract");
            if(contractName is null){continue;}
            var contract=compilation.GetTypeByMetadataName(contractName);
            var module=Text(marker,"ClientModule");var database=Text(marker,"ClientDatabase");
            if(contract is not{TypeKind:TypeKind.Interface,Arity:0}||module is null||database is null||marker.ContainingNamespace.IsGlobalNamespace){
                context.ReportDiagnostic(Diagnostic.Create(Unsupported,marker.Locations.FirstOrDefault(),"ClientContract、ClientModule、ClientDatabaseと公開インターフェースを指定してください。"));
                continue;
            }
            var methods=contract.GetMembers().OfType<IMethodSymbol>().ToArray();
            if(contract.Interfaces.Length!=0||methods.Length==0||methods.Select(static method=>method.Name).Distinct(StringComparer.Ordinal).Count()!=methods.Length||contract.GetMembers().Any(static member=>member is not IMethodSymbol)||methods.Any(static method=>!Supported(method))){
                context.ReportDiagnostic(Diagnostic.Create(Unsupported,marker.Locations.FirstOrDefault(),"Native v1の生成対象は、型付き引数一つとIEnumerable<T>の戻り値を持つ非genericメソッドです。"));
                continue;
            }
            var namespaceName=marker.ContainingNamespace.ToDisplayString();
            var className=contract.Name+"Client";
            if(contract.Name.Length>1&&contract.Name[0]=='I'&&char.IsUpper(contract.Name[1])){className=contract.Name.Substring(1)+"Client";}
            var source=new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            source.AppendLine($"namespace {namespaceName};");
            source.AppendLine($"public sealed partial class {className}{{");
            source.AppendLine("    private readonly global::Seamless.Database.Client.NativeQueryClient connection;");
            source.AppendLine("    private readonly string schemaFingerprint;");
            source.AppendLine($"    public {className}(global::Seamless.Database.Client.NativeQueryClient connection,string schemaFingerprint){{");
            source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(connection);global::System.ArgumentException.ThrowIfNullOrWhiteSpace(schemaFingerprint);");
            source.AppendLine("        this.connection=connection;this.schemaFingerprint=schemaFingerprint;");
            source.AppendLine("    }");
            foreach(var method in methods){
                var argument=method.Parameters[0];var result=((INamedTypeSymbol)method.ReturnType).TypeArguments[0];
                var argumentType=argument.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);var resultType=result.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                source.AppendLine($"    public global::System.Collections.Generic.IAsyncEnumerable<{resultType}> @{method.Name}Async({argumentType} @{argument.Name},global::System.Threading.CancellationToken cancellationToken=default)=>");
                source.AppendLine($"        this.connection.QueryAsync<{argumentType},{resultType}>({Literal(module)},{Literal(method.Name)},{Literal(database)},this.schemaFingerprint,@{argument.Name},cancellationToken);");
            }
            source.AppendLine("}");
            context.AddSource(namespaceName+".NativeClient.g.cs",SourceText.From(source.ToString(),Encoding.UTF8));
        }
    }

    private static bool Supported(IMethodSymbol method)=>method.MethodKind==MethodKind.Ordinary&&!method.IsStatic&&!method.IsGenericMethod
        &&method.Parameters.Length==1&&method.Parameters[0].RefKind==RefKind.None
        &&method.ReturnType is INamedTypeSymbol{Arity:1} result&&result.OriginalDefinition.ToDisplayString()=="System.Collections.Generic.IEnumerable<T>";
    private static string? Text(INamedTypeSymbol marker,string name)=>marker.GetMembers(name).OfType<IFieldSymbol>().FirstOrDefault(static field=>field.IsConst)?.ConstantValue as string;
    private static string Literal(string value)=>Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value,true);
}
