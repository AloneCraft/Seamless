using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
namespace Shared.Database.Generation;

internal sealed partial class DatabaseSchemaGeneration:IIncrementalGenerator {
    private static readonly SymbolDisplayFormat FullTypeFormat=new(
        globalNamespaceStyle:SymbolDisplayGlobalNamespaceStyle.Included,
        typeQualificationStyle:SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions:SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions:SymbolDisplayMiscellaneousOptions.ExpandNullable
            |SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier
            |SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var targets=context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node,_)=>node is TypeDeclarationSyntax,
                static (syntaxContext,_)=>CreateTarget(syntaxContext))
            .Where(static target=>target is not null)
            .Select(static (target,_)=>target!);

        context.RegisterSourceOutput(targets.Collect(),static (productionContext,collected)=>Generate(productionContext,collected));
    }

    private static TypeTarget? CreateTarget(GeneratorSyntaxContext context) {
        var declaration=(TypeDeclarationSyntax)context.Node;
        if(context.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol symbol) {
            return null;
        }
        var compilation=context.SemanticModel.Compilation;
        return new(symbol,declaration.Modifiers.Any(SyntaxKind.PartialKeyword),
            compilation.GetTypeByMetadataName("Seamless.Database.Client.NativeWireLayoutAttribute") is not null,
            compilation.GetTypeByMetadataName("Seamless.Database.Client.INativeReplayDecoder`1") is not null);
    }

    private static void Generate(SourceProductionContext context,ImmutableArray<TypeTarget> targets) {
        if(targets.IsDefaultOrEmpty) {
            return;
        }
        var uniqueTargets=targets
            .GroupBy(static target=>target.Symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),StringComparer.Ordinal)
            .Select(static group=>new TypeTarget(group.First().Symbol,group.Any(static target=>target.IsPartial),
                group.Any(static target=>target.NativeWire),group.Any(static target=>target.ReplayAvailable)))
            .ToArray();
        var markerNamespaces=uniqueTargets
            .Where(static target=>target.Symbol.Name=="DatabaseGenerator")
            .Select(static target=>NamespaceName(target.Symbol.ContainingNamespace))
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        if(markerNamespaces.Length==0) {
            return;
        }
        var collectibleNamespaces=uniqueTargets
            .Where(static target=>target.Symbol.Name=="DatabaseGenerator"&&target.Symbol.GetMembers("Collectible").OfType<IFieldSymbol>().Any(static field=>field.IsConst&&field.ConstantValue is true))
            .Select(static target=>NamespaceName(target.Symbol.ContainingNamespace)).ToArray();
        var optimizedNamespaces=uniqueTargets
            .Where(static target=>target.Symbol.Name=="DatabaseGenerator"&&target.Symbol.GetMembers("OptimizeFieldLayout").OfType<IFieldSymbol>().Any(static field=>field.IsConst&&field.ConstantValue is true))
            .Select(static target=>NamespaceName(target.Symbol.ContainingNamespace)).ToArray();

        var records=uniqueTargets
            .Where(static target=>target.IsPartial
                &&target.Symbol.TypeKind==TypeKind.Struct
                &&target.Symbol.Arity==0
                &&target.Symbol.ContainingType is null)
            .Where(target=>markerNamespaces.Any(root=>IsSchemaNamespace(
                NamespaceName(target.Symbol.ContainingNamespace),root)))
            .Select(static target=>target.Symbol)
            .OrderBy(static symbol=>NamespaceName(symbol.ContainingNamespace),StringComparer.Ordinal)
            .ThenBy(static symbol=>symbol.Name,StringComparer.Ordinal)
            .ToArray();
        if(records.Length==0) {
            return;
        }

        var builder=new StringBuilder();
        var nativeWire=targets.Any(static target=>target.NativeWire);
        var replayAvailable=targets.Any(static target=>target.ReplayAvailable);
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS0164, CS8601, CS8981");
        foreach(var namespaceGroup in records.GroupBy(static symbol=>NamespaceName(symbol.ContainingNamespace),StringComparer.Ordinal)) {
            builder.AppendLine($"namespace {namespaceGroup.Key} {{");
            foreach(var symbol in namespaceGroup) {
                var collectible=collectibleNamespaces.Any(root=>IsSchemaNamespace(NamespaceName(symbol.ContainingNamespace),root));
                var optimized=optimizedNamespaces.Any(root=>IsSchemaNamespace(NamespaceName(symbol.ContainingNamespace),root));
                AppendRecord(builder,symbol,"    ",collectible,optimized,nativeWire,replayAvailable,records,collectibleNamespaces);
            }
            builder.AppendLine("}");
        }
        context.AddSource("Seamless.Database.Schema.g.cs",SourceText.From(builder.ToString(),Encoding.UTF8));
    }

    private static void AppendRecord(StringBuilder builder,INamedTypeSymbol symbol,string indent,bool collectible,bool optimized,bool nativeWire,
        bool replayAvailable,INamedTypeSymbol[] records,string[] collectibleNamespaces) {
        var properties=GetProperties(symbol);
        if(properties.Length==0) {
            return;
        }
        var typeName=symbol.ToDisplayString(FullTypeFormat);
        var replay=replayAvailable&&nativeWire&&CanReplayField(symbol,records,collectibleNamespaces,new(SymbolEqualityComparer.Default));
        var replayContract=$"global::Seamless.Database.Client.INativeReplayDecoder<{typeName}>";
        if(nativeWire&&!collectible){builder.AppendLine($"{indent}[global::Seamless.Database.Client.NativeWireLayoutAttribute(1,new string[]{{{string.Join(",",properties.Select(static property=>global::Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(property.Name,true)))}}})]");}
        if(collectible){builder.AppendLine($"{indent}partial struct {symbol.Name} {{");}
        else{builder.AppendLine($"{indent}partial struct {symbol.Name}:global::MemoryPack.IMemoryPackable<{typeName}>{(replay?","+replayContract:string.Empty)} {{");}
        builder.Append($"{indent}    public {symbol.Name}(");
        for(var index=0;index<properties.Length;index++) {
            if(index>0) {
                builder.Append(',');
            }
            builder.Append($"{TypeName(properties[index].Type)} ");builder.Append(collectible?"@"+properties[index].Name:"value"+index);
        }
        builder.AppendLine(") {");
        if(optimized){builder.AppendLine($"{indent}        this._F=default;");}
        for(var index=0;index<properties.Length;index++) {
            builder.AppendLine($"{indent}        this.{Field(properties[index],index,optimized)}="+(collectible?"@"+properties[index].Name:"value"+index)+";");
        }
        builder.AppendLine($"{indent}    }}");
        builder.AppendLine();
        if(optimized){AppendFields(builder,properties,indent);}
        for(var index=0;index<properties.Length;index++) {
            var field=Field(properties[index],index,optimized);
            if(!optimized){builder.AppendLine($"{indent}    private {TypeName(properties[index].Type)} {field};");}
            var computed=properties[index].GetAttributes().FirstOrDefault(static attribute=>attribute.AttributeClass?.ToDisplayString()=="Seamless.Database.ComputedColumnAttribute");
            var getter=computed is not null&&collectible?$"global::Seamless.Database.GeneratedRowExpression<{typeName}>.Read<{TypeName(properties[index].Type)}>(in this,{computed.ConstructorArguments[0].Value},this.{field})":$"this.{field}";
            builder.AppendLine($"{indent}    public partial {TypeName(properties[index].Type)} {properties[index].Name} {{ get=>{getter}; }}");
        }
        if(collectible){builder.AppendLine($"{indent}}}");return;}
        builder.AppendLine();
        builder.AppendLine($"{indent}    static {symbol.Name}() {{");
        builder.AppendLine($"{indent}        global::MemoryPack.MemoryPackFormatterProvider.Register<{typeName}>();");
        builder.AppendLine($"{indent}    }}");
        builder.AppendLine();
        builder.AppendLine($"{indent}    static void global::MemoryPack.IMemoryPackFormatterRegister.RegisterFormatter() {{");
        builder.AppendLine($"{indent}        if(!global::MemoryPack.MemoryPackFormatterProvider.IsRegistered<{typeName}>()) {{");
        builder.AppendLine($"{indent}            global::MemoryPack.MemoryPackFormatterProvider.Register(new global::MemoryPack.Formatters.MemoryPackableFormatter<{typeName}>());");
        builder.AppendLine($"{indent}        }}");
        builder.AppendLine($"{indent}        if(!global::MemoryPack.MemoryPackFormatterProvider.IsRegistered<{typeName}[]>()) {{");
        builder.AppendLine($"{indent}            global::MemoryPack.MemoryPackFormatterProvider.Register(new global::MemoryPack.Formatters.ArrayFormatter<{typeName}>());");
        builder.AppendLine($"{indent}        }}");
        builder.AppendLine($"{indent}    }}");
        builder.AppendLine();
        builder.AppendLine($"{indent}    static void global::MemoryPack.IMemoryPackable<{typeName}>.Serialize<TBufferWriter>(ref global::MemoryPack.MemoryPackWriter<TBufferWriter> writer,scoped ref {typeName} value) {{");
        for(var index=0;index<properties.Length;index++) {
            builder.AppendLine($"{indent}        {Serialize(properties[index],index,optimized,records)}");
        }
        builder.AppendLine($"{indent}    }}");
        builder.AppendLine();
        builder.AppendLine($"{indent}    static void global::MemoryPack.IMemoryPackable<{typeName}>.Deserialize(ref global::MemoryPack.MemoryPackReader reader,scoped ref {typeName} value) {{");
        for(var index=0;index<properties.Length;index++) {
            builder.AppendLine($"{indent}        {Deserialize(properties[index],index,optimized,records)}");
        }
        builder.AppendLine($"{indent}    }}");
        if(replay){
            builder.AppendLine($"{indent}    static {typeName} {replayContract}.Decode(global::System.ReadOnlySpan<byte> payload) {{");
            builder.AppendLine($"{indent}        // 固定長の行はMemoryPackのraw形式。参照を含む行は生成したフィールド順で読む。");
            builder.AppendLine($"{indent}        if(!global::System.Runtime.CompilerServices.RuntimeHelpers.IsReferenceOrContainsReferences<{typeName}>()){{");
            builder.AppendLine($"{indent}            if(payload.Length!=global::System.Runtime.CompilerServices.Unsafe.SizeOf<{typeName}>()) throw new global::System.IO.InvalidDataException(\"Invalid native replay row length.\");");
            builder.AppendLine($"{indent}            return global::System.Runtime.InteropServices.MemoryMarshal.Read<{typeName}>(payload);");
            builder.AppendLine($"{indent}        }}");
            builder.AppendLine($"{indent}        var reader=new global::MemoryPack.MemoryPackReader(payload,null!);");
            builder.AppendLine($"{indent}        try{{");
            builder.AppendLine($"{indent}            {typeName} value=default;");
            builder.AppendLine($"{indent}            __ReadNativeReplayFields(ref reader,ref value);");
            builder.AppendLine($"{indent}            if(reader.Consumed!=payload.Length) throw new global::System.IO.InvalidDataException(\"Invalid native replay row length.\");");
            builder.AppendLine($"{indent}            return value;");
            builder.AppendLine($"{indent}        }}finally{{reader.Dispose();}}");
            builder.AppendLine($"{indent}    }}");
            builder.AppendLine($"{indent}    internal static void __ReadNativeReplayFields(ref global::MemoryPack.MemoryPackReader reader,ref {typeName} value){{");
            for(var index=0;index<properties.Length;index++){
                builder.AppendLine($"{indent}        {ReadReplayField(properties[index],index,optimized,records)}");
            }
            builder.AppendLine($"{indent}    }}");
        }
        builder.AppendLine($"{indent}}}");
    }

    private static bool IsReplayScalar(ITypeSymbol type){
        if(TryGetNullableValueType(type,out var underlying)){type=underlying;}
        return type.TypeKind==TypeKind.Enum||type.SpecialType is SpecialType.System_String
            or SpecialType.System_Boolean or SpecialType.System_Byte or SpecialType.System_SByte or SpecialType.System_Char
            or SpecialType.System_Int16 or SpecialType.System_UInt16 or SpecialType.System_Int32 or SpecialType.System_UInt32
            or SpecialType.System_Int64 or SpecialType.System_UInt64 or SpecialType.System_Single or SpecialType.System_Double
            or SpecialType.System_Decimal or SpecialType.System_DateTime;
    }

    private static bool CanReplayField(ITypeSymbol type,INamedTypeSymbol[] records,string[] collectibleNamespaces,HashSet<ISymbol> path){
        if(IsReplayScalar(type)){return true;}
        if(type is IArrayTypeSymbol {Rank:1} array){
            var element=array.ElementType;
            return element is not IArrayTypeSymbol&&!TryGetNullableValueType(element,out _)
                &&CanReplayField(element,records,collectibleNamespaces,path)
                &&(IsReplayScalar(element)||HasReplayReference(element,records));
        }
        if(type is not INamedTypeSymbol named||!records.Any(record=>SymbolEqualityComparer.Default.Equals(record,named))
            ||collectibleNamespaces.Any(root=>IsSchemaNamespace(NamespaceName(named.ContainingNamespace),root))
            ||path.Count>=32||!path.Add(named)){return false;}
        var properties=GetProperties(named);
        var supported=properties.Length!=0&&properties.All(property=>CanReplayField(property.Type,records,collectibleNamespaces,path));
        path.Remove(named);
        return supported;
    }

    private static bool HasReplayReference(ITypeSymbol type,INamedTypeSymbol[] records)=>
        type is IArrayTypeSymbol||type.SpecialType==SpecialType.System_String
        ||type is INamedTypeSymbol named&&records.Any(record=>SymbolEqualityComparer.Default.Equals(record,named))
            &&GetProperties(named).Any(property=>HasReplayReference(property.Type,records));

    private static string ReadReplayField(IPropertySymbol property,int index,bool optimized,INamedTypeSymbol[] records){
        var field="value."+Field(property,index,optimized);
        if(property.Type is IArrayTypeSymbol array){
            var element=TypeName(array.ElementType);
            var read=array.ElementType.SpecialType==SpecialType.System_String
                ?"items[i]=reader.ReadString()!;"
                :IsReplayScalar(array.ElementType)?"reader.ReadUnmanaged(out items[i]);":$"{element}.__ReadNativeReplayFields(ref reader,ref items[i]);";
            return $"if(reader.TryReadCollectionHeader(out var count{index})){{var items=new {element}[count{index}];for(var i=0;i<items.Length;i++){{{read}}}{field}=items;}}else{{{field}=null!;}}";
        }
        if(!IsGeneratedUnmanaged(property.Type,records)&&!IsReplayScalar(property.Type)&&property.Type is INamedTypeSymbol nested
            &&records.Any(record=>SymbolEqualityComparer.Default.Equals(record,nested))){
            return $"{TypeName(nested)}.__ReadNativeReplayFields(ref reader,ref {field});";
        }
        return Deserialize(property,index,optimized,records);
    }

    private static bool IsGeneratedUnmanaged(ITypeSymbol type,INamedTypeSymbol[] records,int depth=0){
        if(depth>=32||!type.IsUnmanagedType){return false;}
        if(type is not INamedTypeSymbol named||!records.Any(record=>SymbolEqualityComparer.Default.Equals(record,named))){return true;}
        // Roslynの元シンボルには、これから生成するプロパティ用フィールドがまだない。
        return GetProperties(named).All(property=>IsGeneratedUnmanaged(property.Type,records,depth+1));
    }

    private static ImmutableArray<IPropertySymbol> GetProperties(INamedTypeSymbol symbol) {
        var builder=ImmutableArray.CreateBuilder<IPropertySymbol>();
        foreach(var property in symbol.GetMembers().OfType<IPropertySymbol>()) {
            if(IsPartialDefinition(property)) {
                builder.Add(property);
            }
        }
        return builder.ToImmutable();
    }

    private static bool IsPartialDefinition(IPropertySymbol property) {
        foreach(var reference in property.DeclaringSyntaxReferences) {
            if(reference.GetSyntax() is not PropertyDeclarationSyntax syntax
                ||!syntax.Modifiers.Any(SyntaxKind.PartialKeyword)
                ||syntax.ExpressionBody is not null
                ||syntax.AccessorList?.Accessors.Count!=1) {
                continue;
            }
            var accessor=syntax.AccessorList.Accessors[0];
            if(accessor.IsKind(SyntaxKind.GetAccessorDeclaration)
                &&accessor.Body is null
                &&accessor.ExpressionBody is null) {
                return true;
            }
        }
        return false;
    }

    private static string Serialize(IPropertySymbol property,int index,bool optimized,INamedTypeSymbol[] records) {
        var field="value."+Field(property,index,optimized);
        if(TryGetNullableValueType(property.Type,out var underlyingType)) {
            var write="writer.WritePackable(item);";if(IsGeneratedUnmanaged(underlyingType,records)){write="writer.WriteUnmanaged(item);";}
            return $"writer.WriteUnmanaged({field}.HasValue); if({field}.HasValue) {{ var item={field}.GetValueOrDefault(); {write} }}";
        }
        if(property.Type.SpecialType==SpecialType.System_String) {
            return $"writer.WriteString({field});";
        }
        if(property.Type is IArrayTypeSymbol) {
            return $"writer.WriteArray({field});";
        }
        if(IsGeneratedUnmanaged(property.Type,records)) {
            return $"writer.WriteUnmanaged({field});";
        }
        return $"writer.WritePackable({field});";
    }

    private static string Deserialize(IPropertySymbol property,int index,bool optimized,INamedTypeSymbol[] records) {
        var field="value."+Field(property,index,optimized);
        if(TryGetNullableValueType(property.Type,out var underlyingType)) {
            var read=$"var item{index}=reader.ReadPackable<{TypeName(underlyingType)}>();";if(IsGeneratedUnmanaged(underlyingType,records)){read=$"reader.ReadUnmanaged(out {TypeName(underlyingType)} item{index});";}
            return $"reader.ReadUnmanaged(out bool hasValue{index}); if(hasValue{index}) {{ {read} {field}=item{index}; }} else {{ {field}=null; }}";
        }
        if(property.Type.SpecialType==SpecialType.System_String) {
            return $"{field}=reader.ReadString()!;";
        }
        if(property.Type is IArrayTypeSymbol) {
            return $"reader.ReadArray(ref {field});";
        }
        if(IsGeneratedUnmanaged(property.Type,records)) {
            return $"reader.ReadUnmanaged(out {field});";
        }
        return $"reader.ReadPackable(ref {field});";
    }

    private static bool TryGetNullableValueType(ITypeSymbol type,out ITypeSymbol underlyingType) {
        if(type is INamedTypeSymbol { IsGenericType:true } named
            &&named.OriginalDefinition.SpecialType==SpecialType.System_Nullable_T) {
            underlyingType=named.TypeArguments[0];
            return true;
        }
        underlyingType=type;
        return false;
    }

    private static string TypeName(ITypeSymbol type)=>type.ToDisplayString(FullTypeFormat);

    private static bool IsSchemaNamespace(string candidate,string root) {
        var keys=root.Length==0?"Keys":$"{root}.Keys";
        var records=root.Length==0?"Records":$"{root}.Records";
        return candidate==keys
            ||candidate==records;
    }

    private static string NamespaceName(INamespaceSymbol symbol)=>symbol.IsGlobalNamespace?string.Empty:symbol.ToDisplayString();

    private sealed record TypeTarget(INamedTypeSymbol Symbol,bool IsPartial,bool NativeWire,bool ReplayAvailable);
}
