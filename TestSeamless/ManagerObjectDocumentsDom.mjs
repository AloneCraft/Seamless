export async function verifyObjectDocuments(page, { artifactDirectory }) {
    const { join } = await import('node:path');
    const check = (value, message) => { if (!value) throw new Error(message); };
    const tree = page.getByRole('navigation', { name: 'データベース', exact: true });
    const active = () => page.locator('.対象文書:visible');
    const tab = async (view, name) => {
        await view.getByRole('tab', { name, exact: true }).click();
        await view.locator(`[role="tab"][aria-selected="true"]`).filter({ hasText: new RegExp(`^${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`) }).waitFor();
    };
    const open = async id => {
        await tree.locator(`[data-対象-id="${id}"]`).click();
        await tree.locator(`[data-対象-id="${id}"][data-選択中="true"]`).waitFor();
        await active().waitFor();
        check(await tree.locator('[data-選択中="true"]').count() === 1, 'One selected tree target');
        check(await tree.locator(`[data-対象-id="${id}"]`).getAttribute('data-選択中') === 'true', `Selected tree target ${id}`);
        return active();
    };
    const table = await open('table:Items');
    check(JSON.stringify(await table.getByRole('tab').allTextContents()) === JSON.stringify(['データ', '構造', 'C#', 'アクセス履歴']), 'Table target tabs');
    await tab(table, 'データ');
    const dataRows = table.locator('.結果グリッド領域 tbody tr');
    await dataRows.first().waitFor();
    const rows = await dataRows.count();
    check(rows === 3, 'Actual table data rows exclude the hidden structure grid');
    await tab(table, '構造');
    const types = table.getByRole('combobox', { name: '列の型', exact: true });
    await types.first().waitFor();
    check(await types.count() === 3, 'Three editable structure columns');
    const middle = types.nth(1);
    await middle.focus();
    await middle.selectText();
    await middle.press('ArrowDown');
    check(await types.nth(2).evaluate(element => element === document.activeElement), 'Full selection moves to the next row');
    check(await table.getByRole('listbox').count() === 0, 'Arrow navigation keeps completion closed');
    await types.nth(2).press('F2');
    await types.nth(2).press('ArrowLeft');
    check(await types.nth(2).evaluate(element => element === document.activeElement && element.selectionStart === element.selectionEnd), 'Caret movement edits the same cell');
    await types.nth(2).press('Escape');
    const names = table.getByRole('textbox', { name: '列名', exact: true });
    const originalName = await names.nth(1).inputValue();
    await names.nth(1).fill('DisplayTitle');
    await open('query:Amount');
    await open('table:Items');
    check(await table.getByRole('tab', { name: '構造', exact: true }).getAttribute('aria-selected') === 'true', 'Returning restores the selected target tab');
    check(await names.nth(1).inputValue() === 'DisplayTitle', 'Returning retains unsynchronized structure input');
    await tab(table, 'C#');
    const source = table.getByRole('textbox', { name: '対象のC#', exact: true });
    check((await source.inputValue()).includes('DisplayTitle'), 'Structure synchronizes into target C#');
    check(!(await source.inputValue()).includes('ScalarFunction'), 'Table C# is scoped to its declaration');
    await tab(table, '構造');
    await names.nth(1).fill(originalName);
    await tab(table, 'C#');
    const validSource = await source.inputValue();
    await source.fill(validSource + '\npublic ???');
    await table.getByRole('tab', { name: '構造', exact: true }).click();
    await table.getByRole('alert').first().waitFor();
    check(await table.getByRole('tab', { name: 'C#', exact: true }).getAttribute('aria-selected') === 'true', 'Invalid C# stays in Source');
    check((await source.inputValue()).endsWith('public ???'), 'Invalid C# input is retained');
    check(await table.getByRole('alert').count() > 0, 'Invalid C# exposes diagnostics');
    await source.fill(validSource);
    await tab(table, '構造');
    const tabCount = await page.locator('.文書タブ').count();
    await open('table:Items');
    check(await page.locator('.文書タブ').count() === tabCount, 'Reopening reuses the document');
    const functionView = await open('query:Amount');
    check(await functionView.getByRole('tab', { name: 'データ', exact: true }).getAttribute('aria-selected') === 'true', 'Existing function initially opens Data');
    await functionView.getByRole('textbox', { name: '引数 orderId', exact: true }).fill('10');
    await functionView.getByRole('button', { name: '実行', exact: true }).click();
    await functionView.locator('output').waitFor();
    check((await functionView.locator('output').innerText()).trim() === '6', 'Actual function scalar result');
    const registered = tree.locator('[data-対象-id="query:registered:arithmetic-fork"]');
    check(await registered.count() === 1, 'Registered queries are listed as functions');
    await registered.click();
    await tree.locator('[data-対象-id^="query:registered:"][data-選択中="true"]').waitFor();
    await tab(active(), 'データ');
    await active().getByRole('button', { name: '実行', exact: true }).click();
    await active().locator('output').waitFor();
    check((await active().locator('output').innerText()).trim() === '11', 'Registered function actual scalar result');
    await page.screenshot({ path: join(artifactDirectory, 'registered-function.png'), fullPage: true });
    await tree.locator('[data-対象-id^="db:"]').first().click();
    const databaseInformation = page.getByRole('region', { name: 'DB情報', exact: true });
    await databaseInformation.waitFor();
    const publishedVersion = await databaseInformation.locator('dt').filter({ hasText: /^公開版$/ }).evaluate(element => element.nextElementSibling.textContent.trim());
    check(publishedVersion === 'v1', 'DB information renders its actual published version');
    await page.locator('.対象文書:visible').waitFor({ state: 'hidden' });
    check(await page.locator('.対象文書:visible').count() === 0, 'DB selection opens DB information');
    check(await page.locator('.作業領域 .オブジェクトカード:visible').count() === 0, 'DB information has no duplicate object cards');
    await page.screenshot({ path: join(artifactDirectory, 'database-information.png'), fullPage: true });
    return { objectDocuments: true, tableRows: rows, fullSelectionNavigation: true, caretEditing: true, documentReuse: true, sourceRoundTrip: true, invalidSourceRetained: true, functionValue: 6, registeredFunctionValue: 11 };
}
