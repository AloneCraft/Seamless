    [Fact, Trait("Category","Unit")]
    public void SmokeTest() {
        using var sourceStore = global::Seamless.Stores.HashStore.Create(MemorySize: global::Seamless.Const.LogMemorySize).Create<int>();
        using var sourceSet = sourceStore.Create();
        foreach(var v in new[] { 1,2,3,4 }) sourceSet.Add(v);

        using var secondStore = global::Seamless.Stores.HashStore.Create(MemorySize: global::Seamless.Const.LogMemorySize).Create<int>();
        using var secondSet = secondStore.Create();
        foreach(var v in new[] { 3,4,5 }) secondSet.Add(v);

        using var singleStore = global::Seamless.Stores.HashStore.Create(MemorySize: global::Seamless.Const.LogMemorySize).Create<int>();
        using var singleSet = singleStore.Create();
        singleSet.Add(2);

        using var emptyStore = global::Seamless.Stores.HashStore.Create(MemorySize: global::Seamless.Const.LogMemorySize).Create<int>();
        using var emptySet = emptyStore.Create();

        Assert.True(new HashSet().Smoke(sourceSet,secondSet,singleSet,emptySet)>0);
    }
